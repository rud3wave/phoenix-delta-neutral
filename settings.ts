// ['>5']            — ID 0005 и больше
// ['<5']            — ID 0005 и меньше
// [['1', '100']]    — ID от 0001 до 0100 включительно
// Форматы можно комбинировать: ['3', ['10', '13'], '20', '>100']
// Оставьте [], чтобы использовать все кошельки.
export const ID_FILTER = [];

// Количество попыток при ошибке
