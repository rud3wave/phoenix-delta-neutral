// --- ЛОГИКА ИСПОЛНЕНИЯ ---
// Как открывать и закрывать позиции:
//   'leader-follower' = лидер (крупнейшая позиция) — лимитка (maker), фолловер — маркет (taker) после филла
//   'all-market'      = всё маркетом (быстро, но taker-комиссия со всего объёма)
export const EXECUTION_MODE: 'leader-follower' | 'all-market' = 'leader-follower';

// --- ТОКЕНЫ ---
// Single token → ['ETH'] — все группы торгуют только ETH
// Multi token  → ['ETH', 'SOL', 'BTC'] — каждая группа рандомно выберет один
export const TOKENS_TO_TRADE = ['ETH'];

// --- РИСК (ЭФФЕКТИВНОЕ ПЛЕЧО) ---
// Phoenix работает на кросс-марже: ВЕСЬ баланс кошелька обеспечивает позицию.
// Поэтому риск задаётся одним числом — эффективным плечом:
//   notional = баланс × плечо
//   ликвидация примерно в (100 / плечо)% от цены входа
// Каждый кошелёк берёт случайное плечо из диапазона [мин, макс].
//   [3, 5]   = консервативно (ликвидация далеко, меньше объём)
//   [7, 10]  = средне
//   [10, 15] = агрессивно (ликвидация близко, больше объём)
// Каждый токен должен быть в списке! Максимумы биржи: ETH 25x | SOL 25x | BTC 40x.
export const LEVERAGE = {
  ETH: [7, 10],
  // SOL: [7, 10],
  // BTC: [7, 10],
};

// Минимальная дистанция до ликвидацииации (%). Жёсткий предохранитель:
// плечо автоматически урезается до 100 / MIN_LIQ_DISTANCE_PERCENT.
//   10 → не выше 10x, 5 → не выше 20x.
export const MIN_LIQ_DISTANCE_PERCENT = 10;

// --- ГРУППЫ ---
// [longCount, shortCount] — должно совпадать с количеством кошельков!
// 2 кошелька → [[1, 1]]
// 3 кошелька → [[2, 1]] или [[1, 2]]
// 5 кошельков → [[3, 2]] или [[2, 3]]
export const GROUP_CONFIGS = [[3, 2]];

// --- ОРДЕРА ---

