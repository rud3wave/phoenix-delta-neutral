// Перемешивать кошельки перед запуском
export const SHUFFLE_WALLETS = true;

// Фильтр кошельков по ID. ID равен номеру строки приватного ключа в privatekeys.txt.
// ['5']             — только ID 0005
// ['>5']            — ID 0005 и больше
// ['<5']            — ID 0005 и меньше
// [['1', '100']]    — ID от 0001 до 0100 включительно
// Форматы можно комбинировать: ['3', ['10', '13'], '20', '>100']
// Оставьте [], чтобы использовать все кошельки.
export const ID_FILTER = [];

// Количество попыток при ошибке
export const RETRY = 3;

// --- ЛОГИКА ИСПОЛНЕНИЯ ---
// Как открывать и закрывать позиции. Выбери ОДИН из трёх режимов:
//   'limit'           = обе стороны открываются и закрываются лимитками ОДНОВРЕМЕННО (maker),
//                       при односторонности отстающая сторона доедается маркетом
//   'leader-follower' = открытие: лидер (крупнейшая позиция) — лимитка (maker),
//                       фолловер — маркет (taker) после филла; закрытие — обе лимитками
//   'market'          = всё маркетом (быстро, но taker-комиссия со всего объёма)
export const EXECUTION_MODE = 'limit';

// --- ТОКЕНЫ ---
// Single token → ['ETH'] — все группы торгуют только ETH
// Multi token  → ['ETH', 'SOL', 'BTC'] — каждая группа рандомно выберет один
export const TOKENS_TO_TRADE = ['ETH'];

// --- РИСК (ЭФФЕКТИВНОЕ ПЛЕЧО) ---
// Сумма позиции = баланс кошелька × плечо.
// Пример: на кошельке $600, LEVERAGE [7, 10] →
// позиция откроется примерно на $4200-6000
// (каждый кошелёк берёт случайное плечо из диапазона).
//
// Phoenix работает на кросс-марже: ВЕСЬ баланс обеспечивает позицию,
// поэтому плечо — единственная ручка риска:
//   ликвидация примерно в (100 / плечо)% от цены входа
//   [3, 5]   = консервативно (ликвидация далеко, меньше объём)
//   [7, 10]  = средне
//   [10, 15] = агрессивно (ликвидация близко, больше объём)
//
// Каждый токен должен быть в списке! Максимумы биржи: ETH 25x | SOL 25x | BTC 40x.
export const LEVERAGE = {
  ETH: [7, 10],
  // SOL: [7, 10],
  // BTC: [7, 10],
};

// --- ГРУППЫ ---
// [longCount, shortCount] — должно совпадать с количеством кошельков!
// 2 кошелька → [[1, 1]]
// 3 кошелька → [[2, 1]] или [[1, 2]]
// 5 кошельков → [[3, 2]] или [[2, 3]]
export const GROUP_CONFIGS = [[3, 2]];

// --- ОРДЕРА ---

// Максимальный спред для входа (%)
// Если спред выше — бот ждёт пока сузится
export const MAX_SPREAD = 0.03;

// Фильтр движения цены (%): бот НЕ заходит, пока цена дёргается, и ждёт паузу —
// тогда обе стороны входят почти по одной цене и меньше теряют на разнице.
// Меньше значение = строже фильтр: входы точнее, но заходить будет реже.
// Больше значение = заходит чаще, но входы могут быть дальше друг от друга.
// Обычно менять не нужно.
export const MAX_MID_DRIFT_PERCENT = 0.03;

// Сколько секунд цена должна постоять спокойно перед входом (см. фильтр выше).
// Обычно менять не нужно.
export const MID_STABILITY_WINDOW_SEC = 6;

// Техническая настройка: как часто проверять, что лимитки исполнились (мс).
// Не трогать.
export const FILL_POLL_INTERVAL_MS = 300;

// Сколько секунд ждать филла лимитки, прежде чем снять и переставить.
//   60  = переставлять каждую минуту (агрессивнее, быстрее филлы)
//   120 = переставлять каждые 2 минуты (меньше транзакций)
export const REQUOTE_INTERVAL_SEC = 160;

// Как часто (сек) проверять, что лимитка (на открытии и закрытии) всё ещё первая в стакане.
// Если цена ушла и ордер оказался ниже верха — он сразу снимается и
// переставляется на лучший бид/аск, чтобы лимитка всегда стояла первой.
export const TOP_OF_BOOK_CHECK_SEC = 3;

// --- ОТКРЫТИЕ ---

// Обе стороны открываются лимитками ОДНОВРЕМЕННО (мейкер — комиссия в 7 раз ниже,
// плюс ловится спред) — зеркально закрытию. Пока ни одна не заполнилась —
// портфель плоский. Если одна сторона заполнилась, а вторая не заполнилась
// за X секунд — отстающая открывается маркетом, чтобы не упустить вход.
//   0  = не страховать: ждать филла обеих лимиток (риск вообще не зайти)
//   30 = маркет через 30 секунд односторонности
export const ONE_SIDED_OPEN_TIMEOUT_SEC = 30;

// --- ЗАКРЫТИЕ ---

// Обе стороны закрываются лимитками ОДНОВРЕМЕННО (мейкер, комиссия в 7 раз ниже,
// плюс ловится спред). Пока открыты обе — портфель хеджирован.
// Если одна сторона закрылась, а вторая не заполнилась за X секунд —
// отстающая закрывается маркетом, чтобы не стоять голым.
//   0   = не страховать: ждать филла обеих лимиток (риск простоя в тренде)
//   120 = маркет через 2 минуты односторонности (оптимум)
export const ONE_SIDED_CLOSE_TIMEOUT_SEC = 120;


// --- УДЕРЖАНИЕ ---

// Время удержания позиций перед закрытием (минуты) 
// [0, 0] = держать бесконечно (закрытие вручную через режим 2)
export const HOLD_MINUTES = [1000, 1200];

// Количество торговых циклов (открытие → закрытие = 1 цикл) — одинаково для всех кошельков
export const TRADES_COUNT = 3;

// --- ЗАДЕРЖКИ (секунды) ---

// Задержка между циклами
export const DELAY_BETWEEN_TRADES = [10, 30];

// Интервал опроса биржи (секунды) — как часто бот проверяет статус
export const POLL_INTERVAL_SEC = 5;

